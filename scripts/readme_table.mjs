// Regenerate the leaderboard block in README.md from data/.
//
// A stale leaderboard in the README of a leaderboard is the worst failure this repo
// has available, so the table is never hand-edited: build.sh rewrites it between the
// markers below on every build.
// The instance labels, the quoting convention and the no-record reasons are exported
// because the site (site.mjs) renders the same table in HTML. Two copies of "how an
// instance is named" would drift, and the drift would be invisible until someone
// compared the README against the front page.
import fs from "node:fs";
import path from "node:path";
import { perSiteDivisor, perSiteLabel, isSampled, noErrorMetrics } from "./units.mjs";
import { collect, recordOf, summarize } from "./summary.mjs";
import { citeCell } from "./cite.mjs";
import { sources } from "./enrich_sources.mjs";

const BEGIN = "<!-- BEGIN LEADERBOARD (generated by scripts/readme_table.mjs - do not edit) -->";
const END = "<!-- END LEADERBOARD -->";

// Physics convention: one significant digit of uncertainty in parentheses, and the
// energy quoted to exactly that decimal place. Quoting digits past the error bar is
// how a table invents precision nobody claimed.
export function quote(energy, sigma) {
  // A stated sigma of exactly 0 is how the upstream tables write "deterministic" on an
  // exact diagonalization. There is no last digit for it to qualify, and taking its
  // logarithm asks for infinitely many decimals, so it is quoted like a row with none.
  if (sigma == null || !(sigma > 0)) return { text: energy.toFixed(7), decimals: 7 };
  const rounded = Number(sigma.toPrecision(1));
  const decimals = Math.max(0, -Math.floor(Math.log10(rounded)));
  const digit = Math.round(rounded * 10 ** decimals);
  return { text: `${energy.toFixed(decimals)}(${digit})`, decimals };
}

// Method strings run to 60+ characters and would otherwise be cut mid-word, which
// reads as a typo rather than as an abbreviation.
export function shorten(method, max) {
  if (method.length <= max) return method;
  const cut = method.slice(0, max);
  const at = Math.max(cut.lastIndexOf(" "), cut.lastIndexOf(","));
  return (at > max * 0.6 ? cut.slice(0, at) : cut).replace(/[,(]$/, "") + "...";
}

// Markers shown against a number, in precedence order. A row carrying no error metric
// at all gets the circle and nothing else - the dagger would be redundant, since a
// sampled row with no variance has no sigma either.
export function marks(r) {
  if (noErrorMetrics(r)) return " &#9675;";
  if (isSampled(r.method) && r.sigma == null) return " &dagger;";
  return "";
}

// Every instance is listed, one collapsed table per model, and the reader clicks through
// them; the frontier table (views.mjs) is rendered only on the site. Those labels are built
// from the instance itself, so anything added to data/ appears without a hand-written entry.
export const MODELS = [
  ["Heisenberg", "Heisenberg"],
  ["J1J2", "J1-J2"],
  ["Hubbard", "Hubbard"],
  ["tV", "Spinless t-V"],
  ["TFIsing", "Transverse-field Ising"],
  ["Impurity", "Impurity"],
];

// Boundary codes as defined in vendor/varbench/lattice.md. Periodic is the default and
// goes unsaid, as in the frontier labels.
export const BOUNDARY = { O: "open", PO: "periodic/open", PA: "periodic/antiperiodic" };

export function geometry(inst) {
  const n = inst.n_sites;
  const cells = inst.lattice.match(/^([a-z]+)-(\d+(?:x\d+)+)$/);
  if (cells) {
    const product = cells[2].split("x").reduce((a, b) => a * Number(b), 1);
    return product === n ? `${cells[1]} ${cells[2]}` : `${cells[1]} ${cells[2]} (${n} sites)`;
  }
  const side = Math.sqrt(n);
  if (/^(square|triangular)$/.test(inst.lattice) && Number.isInteger(side))
    return `${inst.lattice} ${side}x${side}`;
  return `${inst.lattice}, ${n} sites`;
}

export function instanceLabel(inst) {
  if (inst.model === "Impurity") return `${inst.lattice}, size ${inst.n_sites}`;
  const p = inst.params ?? {};
  const parts = [geometry(inst)];
  if (BOUNDARY[inst.boundary]) parts.push(BOUNDARY[inst.boundary]);
  for (const k of ["J2", "h", "U", "V"]) if (p[k] != null) parts.push(`${k} = ${p[k]}`);
  if (p.Nf != null) {
    // Filling per site. Hubbard files carry Nf = N_up = N_dn; t-V is spinless.
    const fill = (inst.model === "Hubbard" ? 2 * p.Nf : p.Nf) / inst.n_sites;
    const shown = Number(fill.toFixed(4));
    parts.push(`n ${shown === fill ? "=" : "&asymp;"} ${shown}`);
  }
  // VarBench does not document these Hamiltonian variants, so they are shown as named
  // rather than interpreted.
  for (const v of inst.instance_id.matchAll(/_(t12|UV1V2)(?=_|$)/g)) parts.push(v[1]);
  return parts.join(", ");
}

export function byGeometry(a, b) {
  const key = i => [i.lattice, i.n_sites, i.boundary ?? "", i.params?.Nf ?? 0,
    i.params?.J2 ?? i.params?.h ?? i.params?.U ?? i.params?.V ?? 0, i.instance_id];
  const ka = key(a), kb = key(b);
  for (let k = 0; k < ka.length; k++) {
    if (ka[k] === kb[k]) continue;
    return typeof ka[k] === "number" ? ka[k] - kb[k] : ka[k].localeCompare(kb[k]);
  }
  return 0;
}

// Why an instance has no record, tested in the order summary.mjs counts it, so the cells
// agree with the totals under the table.
export function noRecordReason(inst) {
  const v = inst.rows.filter(r => r.bound_type === "variational");
  if (v.some(r => !r.defect && isSampled(r.method) && r.sigma == null)) return "sampled rows carry no error bar";
  if (inst.rows.some(r => r.bound_type === "exact")) return "solved exactly";
  if (v.some(r => r.defect)) return "every variational row is flagged";
  return "no variational row";
}

const HEADER = ["| instance | record | method | closest challenger |", "|---|---|---|---|"];

function row(inst, label, cache) {
  const rec = recordOf(inst);
  if (!rec) return `| ${label} | no record | ${noRecordReason(inst)} | |`;
  const f = perSiteDivisor(inst) ?? 1;
  const q = quote(rec.energy / f, rec.sigma == null ? null : rec.sigma / f);
  const sorted = [...inst.rows].sort((a, b) => a.energy - b.energy);
  const next = sorted
    .slice(sorted.indexOf(rec) + 1)
    .find(r => r.bound_type === "variational" && !r.defect);
  // Quoted at the record's precision so the two are readable against each other, with
  // the same markers the record cell uses. Each method carries its own source link, so
  // the challenger is as checkable as the record.
  const challenger = next
    ? `${(next.energy / f).toFixed(q.decimals)}${marks(next)} ${shorten(next.method, 34)} ${citeCell(next, cache)}`
    : "none";
  return `| ${label} | **${q.text}**${marks(rec)} | ${shorten(rec.method, 46)} ${citeCell(rec, cache)} | ${challenger} |`;
}

function main() {
  const instances = collect();
  const byId = new Map(instances.map(i => [i.instance_id, i]));
  const s = summarize(instances);
  const cache = sources();

  // Tristan's wording, written into the block on GitHub on 2026-09-15; kept here so the build
  // does not erase it.
  const lines = [];
  lines.push("Every row is one published claim about a Hamiltonian instance, carrying the energy value,");
  lines.push("its error bar (uncertainty of last digit in brackets), the method, the primary reference, ");
  lines.push("and a declared `bound_type` saying what kind of quantity the energy value actually is (either a strict");
  lines.push("variational bound, a fixed-node estimate or a zero-variance extrapolation).");

  const spin = perSiteLabel(byId.get("J1J2/square_100_P_0.5"));
  const site = perSiteLabel(byId.get("Hubbard/square_256_P_112_8"));
  lines.push("");
  lines.push(`Energies are per site: spin models as \`${spin}\`, Hubbard as \`${site}\` (see`);
  lines.push("[units and conventions](DATA.md#units-and-conventions)). **Bold** is the record under");
  // Tristan's wording and line breaks from the same GitHub edit.
  lines.push("[the ranking rules](RULES.md#6-records-and-ties). ");
  lines.push("**&#9675;** marks a row where **we found no error");
  lines.push("metric** (neither an error bar nor an energy variance) in the source we read; ");
  lines.push("**&dagger;** marks a");
  lines.push("sampled energy with a variance but no error bar. ");
  lines.push("Both rows stay in the table and in rank");
  lines.push("order; the marker is an open question regarding ambiguous information (see [error metrics](DATA.md#error-metrics)).");
  lines.push("");
  lines.push(`### All ${s.instances} instances (CLICK ME BELOW)`);
  lines.push("");
  const known = new Set(MODELS.map(([m]) => m));
  for (const inst of instances)
    if (!known.has(inst.model)) throw new Error(`${inst.instance_id}: model ${inst.model} has no MODELS entry`);
  for (const [model, name] of MODELS) {
    const group = instances.filter(i => i.model === model).sort(byGeometry);
    if (!group.length) continue;
    const held = group.filter(i => recordOf(i)).length;
    // GitHub only renders a table inside <details> when a blank line follows <summary>.
    lines.push("<details>");
    lines.push(`<summary><b>${name}</b>: ${group.length} instances, ${held} with a record, energies as <code>${perSiteLabel(group[0])}</code></summary>`);
    lines.push("", ...HEADER, ...group.map(i => row(i, instanceLabel(i), cache)), "", "</details>", "");
  }
  const b = s.blocked_on_sigma;
  lines.push(`Across the whole table: **${s.records.held} of ${s.instances} instances have a record**, from ${s.rows} energies.`);
  lines.push(`Of the ${s.instances - s.records.held} instances without one, ${s.records.none_exact_only} are solved exactly and have nothing to compete`);
  lines.push(`for. Separately, **${b.rows} sampled variational energies across ${b.instances} instances carry no error bar**, so`);
  lines.push(`they are listed and rank for nothing, and ${b.would_take_record} of them sit below their instance's current`);
  lines.push("record. If one of those is your paper, the error bar is the only thing missing.");
  lines.push("");
  lines.push(`And **${s.no_error_metrics} energies carry no error metric we could find** (&#9675;). Those numbers stay in the`);
  lines.push("table and in the ranking; the marker only says the energy still needs verification or a word");
  lines.push("from the people who produced it.");
  lines.push("");
  lines.push("More views of the same data (which records nobody has ever challenged, which have stood");
  lines.push("longest, and whether symmetrising actually wins) are in [the back pages](STATS.md).");

  const readme = fs.readFileSync("README.md", "utf8");
  const i = readme.indexOf(BEGIN);
  const j = readme.indexOf(END);
  if (i < 0 || j < 0) throw new Error("README.md is missing the leaderboard markers");
  // Spliced by index, never by String.replace: a replacement containing $' or $& is
  // interpreted as a match reference and pastes the file back into itself.
  const block = `${BEGIN}\n\n${lines.join("\n")}\n\n${END}`;
  fs.writeFileSync("README.md", readme.slice(0, i) + block + readme.slice(j + END.length));
  console.log(`README.md leaderboard: ${s.instances} instances by model, ${s.records.held}/${s.instances} records held`);
}

// Side effect only when run directly, as in summary.mjs: site.mjs imports the labelling
// and quoting helpers above, and an import must never rewrite README.md as a surprise.
if (process.argv[1] && import.meta.url === `file://${path.resolve(process.argv[1])}`) main();
